"""Study 3 analysis: the rules in gates/study3_plan.md and the prediction scoring rules
committed in predictions.md (c23d17a). Writes results/study3/summary.md + summary.json.

Usage: python scripts/study3_analyze.py [--data DIR] [--out DIR]
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from gate1_analyze import acc, fmt, load

REPO = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(REPO / "results" / "study3"))
    ap.add_argument("--out", default=str(REPO / "results" / "study3"))
    args = ap.parse_args()
    D, O = Path(args.data), Path(args.out)
    st = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
    inj, rdr, base = load(D / "trials_injected.jsonl"), load(D / "trials_reader.jsonl"), load(D / "no_injection.jsonl")
    md = ["# Study 3 — replication + text control: summary tables (generated by scripts/study3_analyze.py)\n",
          "Llama-3.1-8B-Instruct, layer 2, α 5, their prompt and vectors. Chance = 10%.\n"]
    v = st.get("result", {})
    if inj:
        md.append("## Main results (same 400 trials)\n")
        md.append("| condition | accuracy |\n|---|---|")
        md.append(f"| Injected model | {fmt(acc(inj))} |")
        md.append(f"| Clean reader of the copied text | {fmt(acc(rdr, 'reader_correct'))} |")
        md.append(f"\nR1 replication (injected ≥ 200/400): **{'PASS' if v.get('R1_replication_pass') else 'FAIL'}**. "
                  f"R2 loophole (reader ≥ injected − 40): **{v.get('R2_loophole')}**.\n")
        n = len(rdr)
        md.append(f"Copy-back of the injected span: exact in {sum(r['exact_target'] for r in rdr)}/{n}; "
                  f"label copied correctly in {sum(r['label_ok_target'] for r in rdr)}/{n}; "
                  f"mean token accuracy {100 * sum(r['tok_acc_target'] for r in rdr) / max(n, 1):.1f}%; "
                  f"all 10 spans exact in {sum(r['n_exact'] == 10 for r in rdr)}/{n}.\n")
        md.append("## By vector type\n\n| type | injected | reader |\n|---|---|---|")
        for t in ("avg", "last"):
            md.append(f"| {t} | {fmt(acc([r for r in inj if r['vec_type'] == t]))} | "
                      f"{fmt(acc([r for r in rdr if r['vec_type'] == t], 'reader_correct'))} |")
        md.append("\n## By concept\n\n| concept | injected | reader |\n|---|---|---|")
        for c in sorted({r["concept"] for r in inj}):
            md.append(f"| {c} | {fmt(acc([r for r in inj if r['concept'] == c]))} | "
                      f"{fmt(acc([r for r in rdr if r['concept'] == c], 'reader_correct'))} |")
        md.append("\n## By target position (of 40 each)\n")
        md.append("| | " + " | ".join(str(i) for i in range(1, 11)) + " |\n|---|" + "---|" * 10)
        md.append("| injected correct | " + " | ".join(str(sum(r["correct"] for r in inj if r["pos"] == i)) for i in range(1, 11)) + " |")
        md.append("| reader correct | " + " | ".join(str(sum(r["reader_correct"] for r in rdr if r["pos"] == i)) for i in range(1, 11)) + " |")
        ca, cr = Counter(r["pred"] for r in inj), Counter(r["reader_pred"] for r in rdr)
        md.append("| injected answers | " + " | ".join(str(ca.get(i, 0)) for i in range(1, 11)) + " |")
        md.append("| reader answers | " + " | ".join(str(cr.get(i, 0)) for i in range(1, 11)) + " |")
        cb = Counter(r["pred"] for r in base)
        md.append(f"\nNo-injection answers over the {len(base)} sentence draws: " +
                  ", ".join(f"{i}: {cb.get(i, 0)}" for i in range(1, 11)) + "\n")
        bmap = {r["draw_index"]: r["pred"] for r in base}
        mv = [r for r in inj if r["pred"] != bmap.get(r["draw_index"])]
        md.append(f"Injected answer differed from the no-injection answer in {len(mv)}/{len(inj)} trials; "
                  f"{sum(r['correct'] for r in mv)} of those landed on the target (descriptive).\n")
        rk = {(r["concept"], r["vec_type"], r["draw"], r["pos"]): r for r in rdr}
        ex = [r for r in inj if rk.get((r["concept"], r["vec_type"], r["draw"], r["pos"]), {}).get("exact_target")]
        nx = [r for r in inj if not rk.get((r["concept"], r["vec_type"], r["draw"], r["pos"]), {}).get("exact_target", True)]
        md.append(f"Injected accuracy when the injected span was copied back exactly: {fmt(acc(ex))}; "
                  f"when it was not: {fmt(acc(nx))} (descriptive).\n")
        md.append("Mean KL on the injected span: " + f"{sum(r['kl_target'] for r in inj) / len(inj):.3f}\n")
        md.append("Examples of perceived injected spans (first 6 non-exact):\n")
        shown = 0
        for r in rdr:
            if not r["exact_target"] and shown < 6:
                md.append(f"- {r['concept']}/{r['vec_type']}, pos {r['pos']}: “{r['perceived'][r['pos'] - 1]}”")
                shown += 1
        md.append("")

    # --- prediction scoring (rules committed in predictions.md, c23d17a)
    pred = {"Q1": "b", "Q2": "c", "Q3": "a", "Q4": "a", "Q5": "b", "Q6": "b", "Q7": "a"}
    out = {}
    if v.get("complete"):
        ik, rk_ = v["inj_k"], v["reader_k"]
        out["Q1"] = "a" if ik >= 300 else "b" if ik >= 200 else "c" if ik >= 100 else "d"
        out["Q2"] = "a" if rk_ <= 60 else "b" if rk_ <= 160 else "c" if rk_ <= 280 else "d"
        out["Q3"] = "d" if ik < 200 else ("a" if rk_ > ik else "b" if rk_ >= ik - 40 else "c")
        pct = 100 * v["exact_copy_k"] / 400
        out["Q4"] = "a" if pct < 25 else "b" if 35 <= pct <= 65 else "c" if pct > 75 else "no letter"
        ka = sum(r["correct"] for r in inj if r["vec_type"] == "avg")
        kl_ = sum(r["correct"] for r in inj if r["vec_type"] == "last")
        out["Q5"] = "a" if ka - kl_ > 20 else "b" if kl_ - ka > 20 else "c"
        ip = 100 * ik / 400
        out["Q6"] = "a" if ip > 63.7 else "c" if ip < 43.7 else "b"
        out["Q7"] = "a" if sum(r["correct"] for r in inj if r["pos"] in (1, 2)) <= 2 else "b"
    md.append("## Prediction scoring (rules committed before the predictions, c23d17a)\n")
    md.append("| # | researcher | outcome letter | correct? |\n|---|---|---|---|")
    for q in ["Q1", "Q2", "Q3", "Q4", "Q5", "Q6", "Q7"]:
        o = out.get(q, "pending")
        ok = "—" if o in ("pending", "no letter") else ("yes" if o == pred[q] else "no")
        md.append(f"| {q} | {pred[q]} | {o} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "summary.json").write_text(json.dumps({"status": st, "prediction_outcomes": out}, indent=2), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
