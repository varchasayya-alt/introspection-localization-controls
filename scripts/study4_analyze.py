"""Study 4 analysis: the rules in gates/study4_plan.md and the prediction scoring rules committed
in predictions.md (ef2431c). Writes results/study4/summary.md + summary.json.

Usage: python scripts/study4_analyze.py [--data DIR] [--out DIR]
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from gate1_analyze import acc, fmt, load

REPO = Path(__file__).resolve().parents[1]


def bins(k):
    return "a" if k >= 150 else "b" if k >= 100 else "c" if k >= 50 else "d"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(REPO / "results" / "study4"))
    ap.add_argument("--out", default=str(REPO / "results" / "study4"))
    args = ap.parse_args()
    D, O = Path(args.data), Path(args.out)
    st = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
    san = json.loads((D / "sanity.json").read_text()) if (D / "sanity.json").exists() else {}
    I = {a: load(D / f"arm{a}_injected.jsonl") for a in "ABC"}
    R = {a: load(D / f"arm{a}_reader.jsonl") for a in "AB"}
    base = load(D / "no_injection.jsonl")
    v = st.get("result", {})
    md = ["# Study 4 — sentence-only vs label-only injection: summary tables (generated by scripts/study4_analyze.py)\n",
          "Llama-3.1-8B-Instruct, layer 2, α 5, their prompt and vectors; 20 fresh draws shared by all arms. "
          "Chance = 10%.\n"]
    if san:
        md.append(f"Sanity: S7 clean copies exact in {san.get('S7_clean_copy_all_exact_draws')}/20 draws (D3 fix); "
                  f"example label part: “{san.get('S8_example_label')}”, sentence part: “{san.get('S8_example_sentence')}”.\n")
    if I["A"]:
        md.append("## Arms (200 trials each)\n")
        md.append("| arm | push on | injected | clean reader | target copied exactly |\n|---|---|---|---|---|")
        for a, what in (("A", "sentence words"), ("B", "label \"SENTENCE N:\""), ("C", "sentence words, random vector")):
            r = R.get(a, [])
            md.append(f"| {a} | {what} | {fmt(acc(I[a]))} | {fmt(acc(r, 'reader_correct')) if r else '—'} | "
                      f"{(str(sum(x['exact_target'] for x in r)) + '/' + str(len(r))) if r else '—'} |")
        md.append("")
        if v:
            md.append(f"**Main test (arm A, target copied exactly):** {v['A_exact_n']} trials; injected "
                      f"{v['A_exact_inj_k']}/{v['A_exact_n']}, reader {v['A_exact_reader_k']}/{v['A_exact_n']} → "
                      f"**{v['main_test']}** (needs ≥ 40 trials, injected ≥ 50%, reader ≤ 15%).\n")
            md.append(f"**Label test (arm B ≥ 100/200):** {'label highlighting IS a real alternative' if v['B_label_alternative'] else 'below the bar'}.\n")
            md.append(f"**Conclusion (pre-registered table):** **{v['conclusion']}**. Secondary: arm-A loophole rule "
                      f"(all 200) → {v['A_loophole_secondary']}; arm C vs A → {v['C_vs_A']}.\n")
        if R.get("B"):
            rb = R["B"]
            md.append(f"Arm B copy-back: label copied correctly {sum(x['label_ok_target'] for x in rb)}/200, "
                      f"sentence words intact {sum(x['sentence_ok_target'] for x in rb)}/200.\n")
        md.append("## By concept\n\n| concept | A injected | A reader | B injected | B reader | C injected |\n|---|---|---|---|---|---|")
        for c in sorted({x["concept"] for x in I["A"]}):
            f = lambda rs, fld="correct": f"{sum(x[fld] for x in rs if x['concept'] == c)}/{sum(1 for x in rs if x['concept'] == c)}"
            md.append(f"| {c} | {f(I['A'])} | {f(R['A'], 'reader_correct')} | {f(I['B'])} | {f(R['B'], 'reader_correct')} | {f(I['C'])} |")
        md.append("\n## By vector type\n\n| type | A | B | C |\n|---|---|---|---|")
        for t in ("avg", "last"):
            md.append(f"| {t} | " + " | ".join(fmt(acc([x for x in I[a] if x['vec_type'] == t])) for a in "ABC") + " |")
        md.append("\n## By target position (of 20 each)\n")
        md.append("| | " + " | ".join(str(i) for i in range(1, 11)) + " |\n|---|" + "---|" * 10)
        for a in "ABC":
            md.append(f"| {a} correct | " + " | ".join(str(sum(x["correct"] for x in I[a] if x["pos"] == i)) for i in range(1, 11)) + " |")
        for a in "AB":
            md.append(f"| {a} reader correct | " + " | ".join(str(sum(x["reader_correct"] for x in R[a] if x["pos"] == i)) for i in range(1, 11)) + " |")
        cb = Counter(x["pred"] for x in base)
        md.append(f"\nNo-injection answers over the {len(base)} draws: " + ", ".join(f"{i}: {cb.get(i, 0)}" for i in range(1, 11)) + "\n")
        md.append("Mean KL on the pushed tokens: " + ", ".join(
            f"{a} {sum(x['kl_target'] for x in I[a]) / max(len(I[a]), 1):.3f}" for a in "ABC") + "\n")

    # --- prediction scoring (rules committed in predictions.md, ef2431c)
    pred = {"P1": "a", "P2": "a", "P3": "d", "P4": "a", "P5": "b", "P6": "c", "P7": "a"}
    out = {}
    if v.get("complete"):
        k = v["inj_k"]
        out["P1"] = bins(k["A"])
        n, ie, re_ = v["A_exact_n"], v["A_exact_inj_k"], v["A_exact_reader_k"]
        out["P2"] = "d" if n < 40 else ("a" if ie >= 0.5 * n and re_ <= 0.15 * n else "b" if ie < 0.5 * n else "c")
        out["P3"] = bins(k["B"])
        out["P4"] = "a" if k["A"] - k["B"] > 20 else "b" if k["B"] - k["A"] > 20 else "c"
        out["P5"] = "a" if abs(k["C"] - k["A"]) <= 20 else "b" if k["C"] < k["A"] else "c"
        pct = 100 * sum(x["exact_target"] for x in R["A"]) / 200
        out["P6"] = "a" if pct < 25 else "b" if 35 <= pct <= 65 else "c" if pct > 75 else "no letter"
        a_pass, b_alt = v["main_test"] == "PASS", v["B_label_alternative"]
        out["P7"] = "a" if a_pass and not b_alt else "b" if a_pass else "c" if b_alt else "d"
    md.append("## Prediction scoring (rules committed before the predictions, ef2431c)\n")
    md.append("| # | researcher | outcome letter | correct? |\n|---|---|---|---|")
    for q in ["P1", "P2", "P3", "P4", "P5", "P6", "P7"]:
        o = out.get(q, "pending")
        ok = "—" if o in ("pending", "no letter") else ("yes" if o == pred[q] else "no")
        md.append(f"| {q} | {pred[q]} | {o} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "summary.json").write_text(json.dumps({"status": st, "prediction_outcomes": out}, indent=2), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
