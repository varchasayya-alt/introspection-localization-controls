"""Study 2 analysis: the tables fixed in gates/text_intact_plan.md and the prediction scoring
rules committed in predictions.md (229a20d). Writes results/study2/summary.md + summary.json.

Usage: python scripts/study2_analyze.py [--data DIR] [--out DIR]
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from gate1_analyze import acc, fmt, load

REPO = Path(__file__).resolve().parents[1]


def letter_P1(n):
    return "a" if n == 0 else "b" if n <= 5 else "c" if n <= 10 else "d"


def letter_P2(k):
    return "a" if k <= 4 else "b" if k <= 7 else "c" if k <= 15 else "d"


def letter_P6(pct):
    if pct < 25:
        return "a"
    if 35 <= pct <= 65:
        return "b"
    if pct > 75:
        return "c"
    return None  # 25-35% or 65-75%: matches no letter


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(REPO / "results" / "study2"))
    ap.add_argument("--out", default=str(REPO / "results" / "study2"))
    args = ap.parse_args()
    D, O = Path(args.data), Path(args.out)
    status = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
    sanity = json.loads((D / "sanity.json").read_text()) if (D / "sanity.json").exists() else {}
    md = ["# Study 2 — text-intact search: summary tables (generated by scripts/study2_analyze.py)\n",
          "Chance = 10%. Text-intact = clean reader ≤ 4/30 (all 30 reader trials run). "
          "Reader trials stop early at 5 correct (shown as k/n with n < 30).\n"]
    if sanity.get("resid_norm_median_by_layer_set0"):
        md.append("Typical activation size (median per-token norm, practice set): " +
                  ", ".join(f"L{k}: {v}" for k, v in sanity["resid_norm_median_by_layer_set0"].items()) + "\n")
    if sanity.get("C5_no_injection"):
        md.append("No-injection answers (set index: 0 = practice, 1–4 = fresh): " +
                  ", ".join(f"{s}: {v['pred']}" for s, v in sanity["C5_no_injection"].items()) + "\n")

    all_intact = []
    attempts_run = [a for a in (1, 2) if f"practice{a}" in status]
    for a in attempts_run:
        v = status[f"practice{a}"]
        md.append(f"## Practice attempt {a}\n")
        md.append("| layer | r | α | injected | reader | text-intact? | exact copies | injected, pos 1–2 | injected, pos 3–10 | mean KL |")
        md.append("|---|---|---|---|---|---|---|---|---|---|")
        for r in v["table"]:
            md.append(f"| {r['layer']} | {r['r']} | {r['alpha']} | {r['inj_k']}/{r['inj_n']} | "
                      f"{r['reader_k']}/{r['reader_n']} | {'yes' if r['intact'] else 'no'} | "
                      f"{r['exact_copy_k']}/{r['reader_n']} | {r['inj_pos12_k']}/6 | {r['inj_pos3_10_k']}/24 | {r['mean_kl']} |")
            if r["intact"]:
                all_intact.append(dict(r, attempt=a))
        sel = v["selected"]
        md.append(f"\nText-intact settings: **{v['n_intact']}**. Selected: " +
                  (f"**layer {sel['layer']}, r {sel['r']}** (injected {sel['inj_k']}/30, reader {sel['reader_k']}/30)"
                   if sel else "**none**") + f" → **{'PASS' if v['pass'] else 'FAIL'}**\n")
        inj = load(D / f"practice{a}_inj.jsonl")
        ans = Counter(x["pred"] for x in inj)
        md.append("Answer distribution over all injected practice trials (1…10): " +
                  ", ".join(str(ans.get(i, 0)) for i in range(1, 11)) + "\n")

    t = status.get("test")
    if t:
        md.append("## Fresh test (200 trials, new concepts and sentences)\n")
        inj, rdr, rnd = load(D / "test_inj.jsonl"), load(D / "test_reader.jsonl"), load(D / "test_random.jsonl")
        md.append("| condition | accuracy |\n|---|---|")
        md.append(f"| Injected (concept) | {fmt(acc(inj))} |")
        md.append(f"| Clean reader of copied text | {fmt(acc(rdr, 'reader_correct'))} |")
        md.append(f"| Injected (random vector, same α) | {fmt(acc(rnd))} |")
        md.append(f"\nRules: injected ≥ 50/200, reader ≤ 30/200, injected − reader ≥ 20/200 → "
                  f"**{'PASS' if t['pass'] else 'FAIL'}**. Exact copies: {t['exact_copy_k']}/{t['reader_n']}.\n")
        md.append("| target position | " + " | ".join(str(i) for i in range(1, 11)) + " |")
        md.append("|---|" + "---|" * 10)
        md.append("| injected correct (of 20) | " + " | ".join(
            str(sum(x["correct"] for x in inj if x["pos"] == i)) for i in range(1, 11)) + " |")
        md.append("| reader correct (of 20) | " + " | ".join(
            str(sum(x["reader_correct"] for x in rdr if x["pos"] == i)) for i in range(1, 11)) + " |\n")
        md.append("| concept | injected | reader |\n|---|---|---|")
        for w in sorted({x["concept"] for x in inj}):
            md.append(f"| {w} | {fmt(acc([x for x in inj if x['concept'] == w]))} | "
                      f"{fmt(acc([x for x in rdr if x['concept'] == w], 'reader_correct'))} |")
        md.append("")

    # --- prediction scoring (rules committed in predictions.md, 229a20d)
    pred = {"P1": "c", "P2": "a", "P3": "c", "P4": "d", "P5": "d", "P6": "b", "P7": "b"}
    out = {}
    if "practice1" in status and status["practice1"]["complete"]:
        out["P1"] = letter_P1(status["practice1"]["n_intact"])
    best = sorted(all_intact, key=lambda r: (-r["inj_k"], r["r"], r["layer"]))[0] if all_intact else None
    stopped = "STOP" in json.dumps(status) or (attempts_run == [1, 2] and not status["practice2"]["pass"])
    finished = bool(t) or (attempts_run == [1, 2] and status["practice2"].get("complete"))
    if finished:
        out["P2"] = letter_P2(best["inj_k"]) if best else "not scorable"
        if status.get("practice1", {}).get("pass"):
            out["P3"] = "a"
        elif status.get("practice2", {}).get("pass"):
            out["P3"] = "b"
        else:
            out["P3"] = "c"
        if not t:
            out["P4"] = "d"
        elif t["pass"]:
            out["P4"] = "a"
        elif t["inj_k"] < 50:
            out["P4"] = "b"
        else:
            out["P4"] = "c"
        if not any(r["inj_k"] >= 8 for r in all_intact):
            out["P5"] = "d"
        else:
            out["P5"] = {2: "a", 4: "a", 8: "b", 12: "c", 16: "c"}[best["layer"]]
        out["P6"] = (letter_P6(100 * best["exact_copy_k"] / 30) or "no letter") if best else "not scorable"
        if all_intact:
            k12 = sum(r["inj_pos12_k"] for r in all_intact)
            if t:
                k12 += sum(x["correct"] for x in load(D / "test_inj.jsonl") if x["pos"] in (1, 2))
            out["P7"] = "a" if k12 <= 1 else "b"
        else:
            out["P7"] = "not scorable"
    md.append("## Prediction scoring (rules committed before the predictions, 229a20d)\n")
    md.append("| # | researcher | outcome letter | correct? |\n|---|---|---|---|")
    for q in ["P1", "P2", "P3", "P4", "P5", "P6", "P7"]:
        o = out.get(q, "pending")
        ok = "—" if o in ("pending", "not scorable", "no letter") else ("yes" if o == pred[q] else "no")
        md.append(f"| {q} | {pred[q]} | {o} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "summary.json").write_text(json.dumps({"status": status, "prediction_outcomes": out,
                                                "best_text_intact": best, "stopped": stopped}, indent=2), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
