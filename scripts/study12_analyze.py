"""Study 12 analysis: the "unlocked" rule in gates/study12_plan.md §5 and the prediction scoring
rules committed in predictions.md (2e49802). Writes results/study12_summary.md + .json.

Usage: python scripts/study12_analyze.py [--results DIR] [--out DIR]
"""
import argparse
import json
import random
from pathlib import Path

from gate1_analyze import load

REPO = Path(__file__).resolve().parents[1]
MODELS = ("final", "llama", "sft")
NAMES = {"final": "Tülu final", "llama": "Llama-3.1-8B-Instruct", "sft": "Tülu SFT"}
ARMS = {"base": "0 baseline", "info": "a informative", "abl": "b ablation", "both": "c both"}
REPORT_BAR, CTRL_BAR = 20.0, 20.0
PRED = {"P1": "a", "P2": "b", "P3": "b", "P4": "b", "P5": "a", "P6": "a"}


def arm_stats(R, arm, seed):
    rows = [r for r in R if r["arm"] == arm]
    if not rows:
        return None
    m = lambda q, inj: 100 * sum(r["p_yes"] for r in rows if r["question"] == q and r["injected"] == inj) / \
        max(1, sum(1 for r in rows if r["question"] == q and r["injected"] == inj))
    draws = sorted({r["draw_index"] for r in rows})
    per = []
    for d in draws:
        inj = [r["p_yes"] for r in rows if r["draw_index"] == d and r["question"] == "det" and r["injected"]]
        none = [r["p_yes"] for r in rows if r["draw_index"] == d and r["question"] == "det" and not r["injected"]]
        per.append(100 * (sum(inj) / len(inj) - none[0]))
    rng = random.Random(seed)
    bs = sorted(sum(rng.choice(per) for _ in per) / len(per) for _ in range(10000))
    s = {"hits": m("det", True), "fa": m("det", False), "ctl_inj": m("ctl", True), "ctl_none": m("ctl", False),
         "report": sum(per) / len(per), "report_ci": [bs[250], bs[9749]],
         "mass_det": sum(r["yes_no_mass"] for r in rows if r["question"] == "det") / sum(1 for r in rows if r["question"] == "det")}
    s["detection_score_s10"] = s["hits"] - s["ctl_inj"]
    return {k: (round(v, 2) if isinstance(v, float) else [round(x, 2) for x in v] if isinstance(v, list) else v) for k, v in s.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(REPO / "results" / "study12"))
    ap.add_argument("--out", default=str(REPO / "results"))
    args = ap.parse_args()
    RES, O = Path(args.results), Path(args.out)
    seed = json.loads((REPO / "stimuli" / "study12_stimuli.json").read_text(encoding="utf-8"))["bootstrap_seed"]
    md = ["# Study 12 — can the yes/no report be unlocked? (generated by scripts/study12_analyze.py)\n",
          "Points = 100 × mean P(yes). Report score = hits − false alarms (detection question), 95% bootstrap CI "
          "over draws. UNLOCKED: report ≥ 20 with CI > 0, control yes-rates ≤ 20, and (arms b, c) a valid ablation.\n"]
    allres, out = {}, {}
    for name in MODELS:
        D = RES / name
        st = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
        dr = json.loads((D / "direction.json").read_text()) if (D / "direction.json").exists() else {}
        R = load(D / "trials.jsonl")
        md.append(f"## {NAMES[name]}\n")
        if not R:
            md.append(f"Not run (sanity: {st.get('sanity', 'not run')}).\n")
            continue
        c = dr.get("candidates", {}).get(str(dr.get("chosen_layer")), {})
        md.append(f"Refusal direction: layer {dr.get('chosen_layer')}; refused share of held-out harmful prompts "
                  f"{dr.get('baseline_refused_share')} → {c.get('refused_share')} (KL harmless {c.get('mean_kl_harmless')}); "
                  f"ablation valid: **{dr.get('valid')}**.\n")
        md.append("| arm | hits | false alarms | **report (hits − FA)** [95% CI] | control, injected | control, none | "
                  "yes/no mass | verdict |\n|---|---|---|---|---|---|---|---|")
        res = {}
        for arm, label in ARMS.items():
            s = arm_stats(R, arm, seed)
            if s is None:
                md.append(f"| {label} | not run | | | | | | not testable |")
                res[arm] = {"verdict": "not testable"}
                continue
            needs_abl = arm in ("abl", "both")
            unlocked = (s["report"] >= REPORT_BAR and s["report_ci"][0] > 0 and s["ctl_inj"] <= CTRL_BAR
                        and s["ctl_none"] <= CTRL_BAR and (not needs_abl or dr.get("valid")))
            s["verdict"] = "UNLOCKED" if unlocked else ("not testable" if needs_abl and not dr.get("valid") else "not unlocked")
            res[arm] = s
            md.append(f"| {label} | {s['hits']} | {s['fa']} | **{s['report']}** {s['report_ci']} | {s['ctl_inj']} | "
                      f"{s['ctl_none']} | {s['mass_det']} | **{s['verdict']}** |")
        md.append("")
        allres[name] = {"direction": dr, "arms": res}
    # --- prediction scoring (rules 2e49802)
    yn = lambda nm, arm: ("a" if allres[nm]["arms"][arm]["verdict"] == "UNLOCKED" else "b") if nm in allres else None
    for q, nm, arm in (("P1", "final", "info"), ("P2", "final", "abl"), ("P3", "llama", "info"), ("P4", "llama", "abl")):
        if yn(nm, arm):
            out[q] = yn(nm, arm)
    ran = [n for n in ("final", "llama") if n in allres]
    if ran:
        out["P5"] = "a" if any(allres[n]["arms"]["both"].get("verdict") == "UNLOCKED" for n in ran) else "b"
        out["P6"] = "a" if any(s.get("ctl_inj", 0) > CTRL_BAR or s.get("ctl_none", 0) > CTRL_BAR
                               for n in ran for s in allres[n]["arms"].values()) else "b"
    md.append("## Prediction scoring (rules committed before the predictions, 2e49802)\n")
    md.append("| # | researcher | outcome letter | correct? |\n|---|---|---|---|")
    for q in PRED:
        x = out.get(q, "pending")
        ok = "—" if x in ("pending", "not scorable") else ("yes" if x == PRED[q] else "no")
        md.append(f"| {q} | {PRED[q]} | {x} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "study12_summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "study12_summary.json").write_text(json.dumps({"results": allres, "prediction_outcomes": out}, indent=1), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
