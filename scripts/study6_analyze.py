"""Study 6 analysis: the rules in gates/study6_plan.md and the prediction scoring rules committed
in predictions.md (a8cf4f0). Writes results/study6/summary.md + summary.json.

Usage: python scripts/study6_analyze.py [--data DIR] [--out DIR]
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from gate1_analyze import load
from gate1 import wilson

REPO = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(REPO / "results" / "study6"))
    ap.add_argument("--out", default=str(REPO / "results" / "study6"))
    args = ap.parse_args()
    D, O = Path(args.data), Path(args.out)
    st = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
    san = json.loads((D / "sanity.json").read_text()) if (D / "sanity.json").exists() else {}
    ln = json.loads((D / "llama_norms.json").read_text()) if (D / "llama_norms.json").exists() else {}
    v = st.get("result", {})
    A, C, R = load(D / "armA_injected.jsonl"), load(D / "armC_injected.jsonl"), load(D / "armA_reader.jsonl")
    base = load(D / "no_injection.jsonl")
    md = ["# Study 6 — Tülu-3-8B with the Study 4 arm-A protocol: summary (generated by scripts/study6_analyze.py)\n",
          "Tülu-3-8B, the authors' prompt in Tülu's chat format, layer 2, α 5, sentence-words-only push, "
          "vectors recomputed from Tülu; 20 fresh draws × 10 positions.\n",
          f"Sanity: **{st.get('sanity', 'not run')}**; S7 clean copies exact: {san.get('S7_clean_copy_all_exact_draws')}/20.\n"]

    # size report
    size = {}
    if san.get("tulu_norm_mean") and ln.get("mean"):
        rt, rl = 5 / san["tulu_norm_mean"], 5 / ln["mean"]
        size = {"tulu_norm": round(san["tulu_norm_mean"], 3), "llama_norm": round(ln["mean"], 3),
                "tulu_rel": round(rt, 4), "llama_rel": round(rl, 4), "ratio": round(rt / rl, 3)}
        md.append(f"## Injection size (plan §4)\n\nAverage residual norm at the injection point (sentence words): "
                  f"Tülu {size['tulu_norm']}, Llama {size['llama_norm']}. Push size 5 = {100 * rt:.1f}% of Tülu's "
                  f"normal size vs {100 * rl:.1f}% of Llama's. Ratio Tülu ÷ Llama = **{size['ratio']}**.\n")
    cos = san.get("cos_tulu_vs_their_llama", {})
    if cos:
        cv = list(cos.values())
        size["cos_mean"] = round(sum(cv) / len(cv), 4)
        md.append(f"Cosine, Tülu vectors vs the authors' Llama vectors: mean **{size['cos_mean']}** "
                  f"(range {min(cv)} to {max(cv)}).\n")

    if v.get("complete"):
        k, n = v["inj_k"], 200
        lo, hi = wilson(k["A"], n)
        rlo, rhi = wilson(v["reader_k_A"], n)
        clo, chi = wilson(k["C"], n)
        md.append("## Main results (200 trials per arm)\n")
        md.append("| | picks pushed sentence | 95% CI |\n|---|---|---|")
        md.append(f"| Arm A injected (concept) | {k['A']}/200 ({k['A'] / 2:.1f}%) | {lo:.1f}–{hi:.1f}% |")
        md.append(f"| Arm A reader (clean model, copied text) | {v['reader_k_A']}/200 ({v['reader_k_A'] / 2:.1f}%) | {rlo:.1f}–{rhi:.1f}% |")
        md.append(f"| Arm C injected (random) | {k['C']}/200 ({k['C'] / 2:.1f}%) | {clo:.1f}–{chi:.1f}% |")
        md.append(f"\nExact-copy trials: **{v['A_exact_n']}**/200; among them injected {v['A_exact_inj_k']}, "
                  f"reader {v['A_exact_reader_k']}. Main test: **{v['main_test']}**"
                  + (f" ({v['main_fail_reason']})" if v.get("main_fail_reason") else "")
                  + f". Arm C vs A: {v['C_vs_A']}. Conclusion: **{v['conclusion']}**.\n")
        md.append("Answers (1…10): A " + ",".join(str(Counter(r["pred"] for r in A).get(i, 0)) for i in range(1, 11))
                  + "; C " + ",".join(str(Counter(r["pred"] for r in C).get(i, 0)) for i in range(1, 11))
                  + "; no injection (20 draws) " + ",".join(str(Counter(r["pred"] for r in base).get(i, 0)) for i in range(1, 11)) + "\n")
        md.append("## By concept (of 20: 2 draws × 10 positions)\n")
        md.append("| concept | A injected | A reader | A exact copies | C random |\n|---|---|---|---|---|")
        for c in dict.fromkeys(r["concept"] for r in A):
            md.append(f"| {c} | {sum(r['correct'] for r in A if r['concept'] == c)} | "
                      f"{sum(r['reader_correct'] for r in R if r['concept'] == c)} | "
                      f"{sum(r['exact_target'] for r in R if r['concept'] == c)} | "
                      f"{sum(r['correct'] for r in C if r['concept'] == c)} |")
        md.append("\n## By target position (of 20)\n")
        md.append("| | " + " | ".join(str(i) for i in range(1, 11)) + " |\n|---|" + "---|" * 10)
        for name, rows, f in (("A", A, "correct"), ("A reader", R, "reader_correct"), ("C", C, "correct")):
            md.append(f"| {name} | " + " | ".join(str(sum(r[f] for r in rows if r["pos"] == i)) for i in range(1, 11)) + " |")
        md.append("")

    # --- prediction scoring (rules committed in predictions.md, a8cf4f0)
    pred = {"P1": "b", "P2": "b", "P3": "b", "P4": "b", "P5": "a", "P6": "c"}
    out = {}
    if v.get("complete"):
        a = v["inj_k"]["A"]
        out["P1"] = "a" if a >= 150 else "b" if a >= 100 else "c" if a >= 50 else "d"
        ne = v["A_exact_n"]
        out["P2"] = "a" if ne >= 150 else "b" if ne >= 40 else "c"
        out["P3"] = {"PASS": "a", "NOT TESTABLE": "d"}.get(
            v["main_test"], "b" if v.get("main_fail_reason") == "injected < 50%" else "c")
        d = v["inj_k"]["C"] - v["inj_k"]["A"]
        out["P4"] = "a" if abs(d) <= 20 else ("b" if d < 0 else "c")
    elif st.get("sanity", "").startswith("FAIL"):
        out.update({q: "not scorable" for q in ("P1", "P2", "P3", "P4")})
    if "ratio" in size:
        out["P5"] = "a" if 0.9 <= size["ratio"] <= 1.1 else ("b" if size["ratio"] > 1.1 else "c")
    if "cos_mean" in size:
        out["P6"] = "a" if size["cos_mean"] >= 0.9 else "b" if size["cos_mean"] >= 0.5 else "c"
    md.append("## Prediction scoring (rules committed before the predictions, a8cf4f0)\n")
    md.append("| # | researcher | outcome letter | correct? |\n|---|---|---|---|")
    for q in pred:
        o = out.get(q, "pending")
        ok = "—" if o in ("pending", "not scorable") else ("yes" if o == pred[q] else "no")
        md.append(f"| {q} | {pred[q]} | {o} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "summary.json").write_text(json.dumps({"status": st, "size": size, "prediction_outcomes": out}, indent=2),
                                    encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
