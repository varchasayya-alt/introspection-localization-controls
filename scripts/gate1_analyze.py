"""Gate 1/2 analysis: only the analyses fixed in gates/gate1_plan.md and the prediction
scoring rules fixed in predictions.md. Reads the per-trial JSONL files and writes
results/gate1/summary.md and results/gate1/summary.json.

Usage: python scripts/gate1_analyze.py [--data DIR] [--out DIR]
"""
import argparse
import json
import math
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def load(path):
    recs = {}
    if not path.exists():
        return []
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if line:
            try:
                r = json.loads(line)
                recs[r["key"]] = r
            except json.JSONDecodeError:
                pass
    return list(recs.values())


def wilson(k, n, z=1.96):
    if n == 0:
        return (None, None)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (round(100 * (c - h), 1), round(100 * (c + h), 1))


def acc(recs, field="correct"):
    n = len(recs)
    k = sum(bool(r[field]) for r in recs)
    lo, hi = wilson(k, n)
    return {"k": k, "n": n, "pct": round(100 * k / n, 1) if n else None, "ci": [lo, hi]}


def fmt(a):
    if not a or not a["n"]:
        return "—"
    return f"{a['pct']}% ({a['k']}/{a['n']}; 95% CI {a['ci'][0]}–{a['ci'][1]})"


def terciles(recs, field):
    xs = sorted(r[field] for r in recs)
    n = len(xs)
    if n < 3:
        return []
    c1, c2 = xs[n // 3], xs[2 * n // 3]
    groups = [[r for r in recs if r[field] < c1], [r for r in recs if c1 <= r[field] < c2],
              [r for r in recs if r[field] >= c2]]
    return [(name, acc(g), round(sum(r[field] for r in g) / max(len(g), 1), 4))
            for name, g in zip(["low", "middle", "high"], groups)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(REPO / "results" / "gate1"))
    ap.add_argument("--out", default=str(REPO / "results" / "gate1"))
    args = ap.parse_args()
    D, O = Path(args.data), Path(args.out)
    stim = json.loads((REPO / "stimuli" / "gate1_stimuli.json").read_text(encoding="utf-8"))
    status = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
    sanity = json.loads((D / "sanity.json").read_text()) if (D / "sanity.json").exists() else {}
    A, B = load(D / "phaseA.jsonl"), load(D / "phaseB.jsonl")
    C1, C3, C6 = load(D / "C1_reader.jsonl"), load(D / "C3_random.jsonl"), load(D / "C6_literal.jsonl")
    S, md = {}, []

    md.append("# Gate 1 / Gate 2 — summary tables (generated by scripts/gate1_analyze.py)\n")
    md.append("Chance = 10%. CI = 95% Wilson interval.\n")

    # --- Phase A
    layers = sorted({r["layer"] for r in A})
    alphas = sorted({r["alpha"] for r in A})
    cell = defaultdict(list)
    for r in A:
        cell[(r["layer"], r["alpha"])].append(r)
    md.append("## Phase A — calibration sweep (30 trials per cell; pass = best cell ≥ 9/30)\n")
    md.append("| layer \\ α | " + " | ".join(str(a) for a in alphas) + " |")
    md.append("|---|" + "---|" * len(alphas))
    for lay in layers:
        row = []
        for a in alphas:
            g = cell.get((lay, a), [])
            row.append(f"{sum(r['correct'] for r in g)}/{len(g)}" if g else "—")
        md.append(f"| {lay} | " + " | ".join(row) + " |")
    S["A"] = {f"L{k[0]}|a{k[1]}": acc(v) for k, v in cell.items()}
    if "A" in status:
        a = status["A"]
        md.append(f"\nSelected cell (rule: most correct, tie → lower α, then lower layer): **layer "
                  f"{a['best_layer']}, α {a['best_alpha']}** = {a['best_correct']}/{a['n']} → "
                  f"**{'PASS' if a['pass'] else 'FAIL'}**\n")
        rn = sanity.get("resid_norm_median_by_layer_set0", {})
        if rn:
            md.append("Typical activation size (median per-token norm, sentence tokens, set 0): " +
                      ", ".join(f"L{k}: {v}" for k, v in rn.items()) + "\n")

    # --- C5
    if sanity.get("C5_no_injection"):
        md.append("## C5 — no injection (which sentence the model names when nothing is injected)\n")
        md.append(", ".join(f"set {s}: {v['pred']}" for s, v in sanity["C5_no_injection"].items()) + "\n")

    # --- Phase B
    if B:
        aB = acc(B)
        S["B"] = aB
        md.append("## Phase B — confirmatory test (300 new trials; pass = ≥ 90/300)\n")
        md.append(f"Accuracy: **{fmt(aB)}** → **{'PASS' if status.get('B', {}).get('pass') else 'FAIL'}**\n")
        md.append("| concept | accuracy |\n|---|---|")
        for w in stim["concepts_test"]:
            md.append(f"| {w} | {fmt(acc([r for r in B if r['concept'] == w]))} |")
        md.append("\n| target position | " + " | ".join(str(i) for i in range(1, 11)) + " |")
        md.append("|---|" + "---|" * 10)
        md.append("| correct (of 30) | " + " | ".join(
            str(sum(r["correct"] for r in B if r["pos"] == i)) for i in range(1, 11)) + " |")
        ans = Counter(r["pred"] for r in B)
        md.append("| answers given | " + " | ".join(str(ans.get(i, 0)) for i in range(1, 11)) + " |\n")

    # --- Gate 2
    if C1 or C3 or C6:
        md.append("## Gate 2 — cheap-trick controls (same cell as Phase B)\n")
        rc = set(stim["concepts_reader_and_literal"])
        B150 = [r for r in B if r["concept"] in rc]
        inj, rdr = acc(B150), acc(C1, "reader_correct")
        S["gate2"] = {"injected_same150": inj, "reader": rdr, "random": acc(C3), "literal": acc(C6)}
        md.append("| condition | accuracy |\n|---|---|")
        md.append(f"| Injected model, same 150 trials as the reader (B: {', '.join(sorted(rc))}) | {fmt(inj)} |")
        md.append(f"| **C1** clean reader given the perceived text | {fmt(rdr)} |")
        md.append(f"| **C3** random vectors (300) | {fmt(acc(C3))} |")
        md.append(f"| **C6** concept word typed into the sentence, no injection | {fmt(acc(C6))} |")
        if C1:
            margin = round(inj["pct"] - rdr["pct"], 1)
            g2 = status.get("gate2", {})
            md.append(f"\nInjected − reader = **{margin} points** (pass needs ≥ 15 and reader < 30%) → "
                      f"**{'PASS' if g2.get('pass') else 'FAIL'}**. Label from C3: **{g2.get('random_label')}**.\n")
            ex = sum(r["exact_target"] for r in C1)
            ta = sum(r["tok_acc_target"] for r in C1) / len(C1)
            S["C2"] = {"exact_target_pct": round(100 * ex / len(C1), 1), "mean_token_acc": round(ta, 3)}
            md.append(f"**C2 copy fidelity:** target sentence copied back exactly in "
                      f"{S['C2']['exact_target_pct']}% of trials ({ex}/{len(C1)}); mean token accuracy "
                      f"{100 * ta:.1f}%. Exact copy of all 10 sentences: "
                      f"{sum(r['exact_all'] for r in C1)}/{len(C1)}.\n")
            # injected accuracy split by whether the copy was exact (descriptive)
            bmap = {(r["concept"], r["set"], r["pos"]): r for r in B150}
            ex_ok = [bmap[(r["concept"], r["set"], r["pos"])] for r in C1 if r["exact_target"] and (r["concept"], r["set"], r["pos"]) in bmap]
            ex_no = [bmap[(r["concept"], r["set"], r["pos"])] for r in C1 if not r["exact_target"] and (r["concept"], r["set"], r["pos"]) in bmap]
            md.append(f"Injected-model accuracy when the target was copied exactly: {fmt(acc(ex_ok))}; "
                      f"when it was not: {fmt(acc(ex_no))}.\n")
            md.append("Examples of perceived target sentences (first 6 non-exact):\n")
            shown = 0
            for r in C1:
                if not r["exact_target"] and shown < 6:
                    orig = stim["sentence_sets"][r["set"]][r["pos"] - 1]
                    md.append(f"- {r['concept']}, set {r['set']}, pos {r['pos']}: “{orig}” → “{r['perceived'][r['pos'] - 1]}”")
                    shown += 1
            md.append("")
    # --- C4, C7 (descriptive)
    if B:
        md.append("## C4 — relatedness of concept and target sentence (descriptive)\n")
        md.append("| cos(concept, sentence) tercile | accuracy | mean cos |\n|---|---|---|")
        for name, a, m in terciles(B, "cos_concept_sentence"):
            md.append(f"| {name} | {fmt(a)} | {m} |")
        md.append("\n## C7 — perturbation size (KL on target-sentence predictions, descriptive)\n")
        md.append("| KL tercile (Phase B) | accuracy | mean KL |\n|---|---|---|")
        for name, a, m in terciles(B, "kl_target"):
            md.append(f"| {name} | {fmt(a)} | {m} |")
        if C3:
            mk = lambda rs: round(sum(r["kl_target"] for r in rs) / len(rs), 4)
            md.append(f"\nMean KL: concept vectors {mk(B)}, random vectors {mk(C3)}.\n")
            md.append("| KL tercile (C3 random) | accuracy | mean KL |\n|---|---|---|")
            for name, a, m in terciles(C3, "kl_target"):
                md.append(f"| {name} | {fmt(a)} | {m} |")
            md.append("")

    # --- prediction scoring (rules from predictions.md)
    md.append("## Prediction scoring (rules fixed in predictions.md before the run)\n")
    sc = {}
    if "A" in status and A:
        best = status["A"]["best_correct"]
        sc["Q1_implied_A>=30%"] = best >= 9
    if B:
        sc["Q1 c (B >= 30%)"] = S["B"]["k"] >= 90
    if C3 and B:
        sc["Q2 a (random within 10 pts)"] = abs(acc(C3)["pct"] - S["B"]["pct"]) <= 10
    if C1:
        sc["Q3 b (reader > 10 pts below injected)"] = (S["gate2"]["injected_same150"]["pct"] - S["gate2"]["reader"]["pct"]) > 10
        sc["Q5 b (exact copy 35-65%)"] = 35 <= S["C2"]["exact_target_pct"] <= 65
    if "A" in status:
        sc["Q4 c (best layer > 4; only layers 1-8 tested)"] = status["A"]["best_layer"] > 4
    if B and status.get("B", {}).get("pass") and "gate2" in status:
        sc["Q6/Q7 b (G1 pass, G2 pass, B < 50%)"] = bool(status["gate2"]["pass"]) and S["B"]["pct"] < 50
    S["prediction_scores"] = sc
    md.append("| prediction | correct? |\n|---|---|")
    for k, v in sc.items():
        md.append(f"| {k} | {'yes' if v else 'no'} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "summary.json").write_text(json.dumps({"status": status, "stats": S}, indent=2), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())  # Windows console is cp1252


if __name__ == "__main__":
    main()
