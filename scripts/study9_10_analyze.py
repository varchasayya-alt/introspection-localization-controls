"""Studies 9-10 analysis: the rules in gates/study9_10_plan.md and the prediction scoring rules
committed in predictions.md (e5841f5). Writes results/study9_10_summary.md + .json.

Usage: python scripts/study9_10_analyze.py [--results DIR] [--out DIR]
"""
import argparse
import json
import random
from collections import Counter
from pathlib import Path

from gate1_analyze import load
from gate1 import wilson

REPO = Path(__file__).resolve().parents[1]
CKPTS = ("sft", "dpo", "final")
LOC = {"sft": 186, "dpo": 185, "final": 186}  # arm-A localization of 200, Studies 7, 8, 6
PRED = {"P1": "a", "P2": "a", "P3": "a", "P4": "a", "P5": "b", "P6": "b", "P7": "a", "P8": "a"}


def jload(p):
    return json.loads(p.read_text()) if p.exists() else {}


def per_draw_scores(rows):
    """Per draw: mean P(yes) detection-injected minus mean P(yes) control-injected."""
    out = {}
    for di in sorted({r["draw_index"] for r in rows}):
        d = [r["p_yes"] for r in rows if r["draw_index"] == di and r["question"] == "det" and r["injected"]]
        c = [r["p_yes"] for r in rows if r["draw_index"] == di and r["question"] == "ctl" and r["injected"]]
        out[di] = 100 * (sum(d) / len(d) - sum(c) / len(c))
    return out


def ci(vals_fn, draws, seed, n=10000):
    rng = random.Random(seed)
    bs = sorted(vals_fn([rng.choice(draws) for _ in draws]) for _ in range(n))
    return round(bs[int(0.025 * n)], 2), round(bs[int(0.975 * n) - 1], 2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(REPO / "results"))
    ap.add_argument("--out", default=str(REPO / "results"))
    args = ap.parse_args()
    RES, O = Path(args.results), Path(args.out)
    seed = json.loads((REPO / "stimuli" / "study10_stimuli.json").read_text(encoding="utf-8"))["bootstrap_seed"]
    md = ["# Studies 9–10 — summary (generated by scripts/study9_10_analyze.py)\n"]
    out, summ = {}, {"study10": {}, "study9": {}}

    # ------------------------------------------------------------------ Study 10
    md.append("## Study 10 — yes/no detection across the Tülu ladder\n")
    md.append("Points = 100 × P(yes). Detection score = P(yes | detection, injected) − P(yes | control, injected). "
              "95% bootstrap CIs over the 20 draws.\n")
    md.append("| checkpoint | detection score | P(yes) det, injected | P(yes) control, injected | false alarm (det, none) | "
              "P(yes) control, none | control answered no | valid |")
    md.append("|---|---|---|---|---|---|---|---|")
    S10 = {}
    for c in CKPTS:
        st = jload(RES / "study10" / c / "status.json").get("result", {})
        rows = load(RES / "study10" / c / "trials.jsonl")
        if not st.get("complete"):
            md.append(f"| {c} | not complete | | | | | | |")
            continue
        pdraw = per_draw_scores(rows)
        draws = sorted(pdraw)
        lo, hi = ci(lambda s: sum(pdraw[d] for d in s) / len(s), draws, seed)
        S10[c] = {"score": st["detection_score_pts"], "ci": [lo, hi], "per_draw": pdraw, "valid": st["valid"],
                  "false_alarm": st["false_alarm_pts"]}
        md.append(f"| {c} | **{st['detection_score_pts']}** ({lo} to {hi}) | {100 * st['p_yes_det_inj']:.1f} | "
                  f"{100 * st['p_yes_ctl_inj']:.1f} | {st['false_alarm_pts']} | {100 * st['p_yes_ctl_none']:.1f} | "
                  f"{st['ctl_none_answered_no']}/20 | {'yes' if st['valid'] else 'NO'} |")
    split = None
    if len(S10) == 3:
        diffs = {}
        for c in ("dpo", "final"):
            dd = sorted(set(S10[c]["per_draw"]) & set(S10["sft"]["per_draw"]))
            f = lambda s, c=c: sum(S10[c]["per_draw"][d] - S10["sft"]["per_draw"][d] for d in s) / len(s)
            diffs[c] = {"diff": round(S10[c]["score"] - S10["sft"]["score"], 2), "ci": ci(f, dd, seed)}
        loc_ok = all(LOC[c] >= 150 for c in CKPTS)
        valid = all(S10[c]["valid"] for c in CKPTS)
        higher = all(diffs[c]["diff"] >= 20 and diffs[c]["ci"][0] > 0 for c in ("dpo", "final"))
        split = "supported" if (loc_ok and valid and higher) else ("not testable" if not valid else "not supported")
        md.append(f"\nDifference vs SFT: DPO {diffs['dpo']['diff']} ({diffs['dpo']['ci'][0]} to {diffs['dpo']['ci'][1]}); "
                  f"final {diffs['final']['diff']} ({diffs['final']['ci'][0]} to {diffs['final']['ci'][1]}). "
                  f"Localization (Studies 6–8): SFT {LOC['sft'] / 2}%, DPO {LOC['dpo'] / 2}%, final {LOC['final'] / 2}%.\n")
        md.append(f"**Sensing-vs-reporting split: {split}.**\n")
        summ["study10"] = {"scores": {c: {k: v for k, v in S10[c].items() if k != "per_draw"} for c in S10},
                           "diffs": diffs, "split": split}

    # ------------------------------------------------------------------ Study 9
    D = RES / "study9"
    st9, san9 = jload(D / "status.json"), jload(D / "sanity.json")
    v = st9.get("result", {})
    md.append("## Study 9 — base model (Llama-3.1-8B), few-shot localization\n")
    md.append(f"Sanity: **{st9.get('sanity', 'not run')}**; positive control (visible ALL CAPS): "
              f"{san9.get('positive_control_correct')}/50 (pass ≥ 35); S7 clean copies exact: "
              f"{san9.get('S7_clean_copy_all_exact_draws')}/20.\n")
    if v.get("complete"):
        A, C, R = load(D / "armA_injected.jsonl"), load(D / "armC_injected.jsonl"), load(D / "armA_reader.jsonl")
        base = load(D / "no_injection.jsonl")
        k = v["inj_k"]
        lo, hi = wilson(k["A"], 200)
        md.append("| | result |\n|---|---|")
        md.append(f"| Arm A (concept) | **{k['A']}/200 ({k['A'] / 2:.1f}%)**, CI {lo}–{hi}% |")
        md.append(f"| Reader | {v['reader_k_A']}/200 |")
        md.append(f"| Exact-copy trials | {v['A_exact_n']}; injected {v['A_exact_inj_k']}, reader {v['A_exact_reader_k']} |")
        md.append(f"| Main test | **{v['main_test']}**{' (' + v['main_fail_reason'] + ')' if v.get('main_fail_reason') else ''} |")
        md.append(f"| Arm C (random) | {k['C']}/200 ({k['C'] / 2:.1f}%) |")
        md.append("\nAnswers (1…10): A " + ",".join(str(Counter(r["pred"] for r in A).get(i, 0)) for i in range(1, 11))
                  + "; C " + ",".join(str(Counter(r["pred"] for r in C).get(i, 0)) for i in range(1, 11))
                  + "; no injection " + ",".join(str(Counter(r["pred"] for r in base).get(i, 0)) for i in range(1, 11)) + "\n")
        md.append("| concept | A | reader | exact copies | C |\n|---|---|---|---|---|")
        for cc in dict.fromkeys(r["concept"] for r in A):
            md.append(f"| {cc} | {sum(r['correct'] for r in A if r['concept'] == cc)} | "
                      f"{sum(r['reader_correct'] for r in R if r['concept'] == cc)} | "
                      f"{sum(r['exact_target'] for r in R if r['concept'] == cc)} | "
                      f"{sum(r['correct'] for r in C if r['concept'] == cc)} |")
        md.append("")
        summ["study9"] = v

    # ------------------------------------------------------------------ predictions (rules e5841f5)
    if "positive_control_correct" in san9:
        out["P1"] = "a" if san9["positive_control_correct"] >= 35 else "b"
        if out["P1"] == "b":
            out.update({q: "not scorable" for q in ("P2", "P3", "P4")})
    if v.get("complete") and out.get("P1") == "a":
        a = v["inj_k"]["A"]
        out["P2"] = "a" if a >= 150 else "b" if a >= 100 else "c" if a >= 50 else "d"
        out["P3"] = {"PASS": "a", "NOT TESTABLE": "d"}.get(v["main_test"], "b" if v.get("main_fail_reason") == "injected < 50%" else "c")
        dd = v["inj_k"]["C"] - a
        out["P4"] = "a" if abs(dd) <= 20 else ("b" if dd < 0 else "c")
    bins = lambda x: "a" if x < 10 else ("b" if x <= 30 else "c")
    if "sft" in S10:
        out["P5"] = bins(S10["sft"]["score"])
    if "final" in S10:
        out["P6"] = bins(S10["final"]["score"])
        fa = S10["final"]["false_alarm"]
        out["P8"] = "a" if fa < 20 else ("b" if fa <= 50 else "c")
    if split:
        out["P7"] = "a" if split == "supported" else "b"
    md.append("## Prediction scoring (rules committed before the predictions, e5841f5)\n")
    md.append("| # | researcher | outcome letter | correct? |\n|---|---|---|---|")
    for q in PRED:
        x = out.get(q, "pending")
        ok = "—" if x in ("pending", "not scorable") else ("yes" if x == PRED[q] else "no")
        md.append(f"| {q} | {PRED[q]} | {x} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "study9_10_summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "study9_10_summary.json").write_text(json.dumps({"summary": summ, "prediction_outcomes": out}, indent=2, default=str),
                                              encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
