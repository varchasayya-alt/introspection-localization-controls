"""Study 5 analysis: the rules in gates/study5_plan.md and the prediction scoring rules committed
in predictions.md (ab0e61c). Writes results/study5/summary.md + summary.json.

Usage: python scripts/study5_analyze.py [--data DIR] [--out DIR]
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from gate1_analyze import load

REPO = Path(__file__).resolve().parents[1]
ARMS = [(q, v) for q in ("Q0", "Q1", "Q2") for v in ("concept", "random")]
NAMES = {"Q0": "Q0 original (injected thought?)", "Q1": "Q1 longest?", "Q2": "Q2 like most?"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=str(REPO / "results" / "study5"))
    ap.add_argument("--out", default=str(REPO / "results" / "study5"))
    args = ap.parse_args()
    D, O = Path(args.data), Path(args.out)
    st = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
    v = st.get("result", {})
    R = {arm: load(D / f"{arm[0]}_{arm[1]}.jsonl") for arm in ARMS}
    base = load(D / "no_injection.jsonl")
    md = ["# Study 5 — question-specificity control: summary tables (generated by scripts/study5_analyze.py)\n",
          "Llama-3.1-8B-Instruct, layer 2, α 5, sentence-words-only push; 20 draws (one 6-word + nine 4-word "
          "sentences) shared by all arms. Pull = accuracy − no-injection hit rate (= accuracy − 10 points).\n"]
    if v.get("arms"):
        md.append("## Pull by question and vector (200 trials each)\n")
        md.append("| question | concept: picks pushed sentence | concept pull | random: picks pushed sentence | random pull |")
        md.append("|---|---|---|---|---|")
        for q in ("Q0", "Q1", "Q2"):
            c, r = v["arms"][f"{q}_concept"], v["arms"][f"{q}_random"]
            md.append(f"| {NAMES[q]} | {c['hits']}/{c['n']} ({c['acc_pct']}%) | **{c['pull_pts']}** | "
                      f"{r['hits']}/{r['n']} ({r['acc_pct']}%) | {r['pull_pts']} |")
        md.append(f"\nValidity (Q0-concept pull ≥ 50): **{'yes' if v['valid'] else 'NO'}**. Labels: "
                  f"Q1 → **{v['labels'].get('Q1')}**, Q2 → **{v['labels'].get('Q2')}**. "
                  f"Overall: **{v['overall']}**.\n")
        md.append(f"Q1 correctness (picks the truly longest sentence): with push {v['Q1_longest_correct_with_push_pct']}% "
                  f"vs no push {v['Q1_longest_correct_no_push_pct']}%.\n")
        cb = {q: Counter(b["pred"] for b in base if b["question"] == q) for q in ("Q0", "Q1", "Q2")}
        md.append("No-injection answers per question (1…10): " + "; ".join(
            f"{q}: " + ",".join(str(cb[q].get(i, 0)) for i in range(1, 11)) for q in cb) + "\n")
        md.append("## Answers given with the concept push (1…10, 200 trials)\n")
        for q in ("Q0", "Q1", "Q2"):
            ca = Counter(r["pred"] for r in R[(q, "concept")])
            md.append(f"- {q}: " + ", ".join(str(ca.get(i, 0)) for i in range(1, 11)))
        md.append("\n## By concept (concept vectors; picks pushed sentence, of 20)\n")
        md.append("| concept | Q0 | Q1 | Q2 |\n|---|---|---|---|")
        for c in sorted({r["concept"] for r in R[("Q0", "concept")]}):
            md.append(f"| {c} | " + " | ".join(str(sum(r["correct"] for r in R[(q, "concept")] if r["concept"] == c))
                                              for q in ("Q0", "Q1", "Q2")) + " |")
        md.append("\n## By target position (concept vectors; of 20)\n")
        md.append("| | " + " | ".join(str(i) for i in range(1, 11)) + " |\n|---|" + "---|" * 10)
        for q in ("Q0", "Q1", "Q2"):
            md.append(f"| {q} | " + " | ".join(str(sum(r["correct"] for r in R[(q, "concept")] if r["pos"] == i))
                                              for i in range(1, 11)) + " |")
        q1 = R[("Q1", "concept")]
        tl = [r for r in q1 if r["pos"] == r["longest_pos"]]
        nl = [r for r in q1 if r["pos"] != r["longest_pos"]]
        md.append(f"\nQ1 split: pushed sentence IS the longest → picks it {sum(r['correct'] for r in tl)}/{len(tl)}; "
                  f"pushed sentence is NOT the longest → picks the pushed one {sum(r['correct'] for r in nl)}/{len(nl)}, "
                  f"picks the longest {sum(r['pred'] == r['longest_pos'] for r in nl)}/{len(nl)}.\n")

    # --- prediction scoring (rules committed in predictions.md, ab0e61c)
    pred = {"P1": "a", "P2": "a", "P3": "a", "P4": "b", "P5": "a", "P6": "a", "P7": "a"}
    out = {}
    if v.get("complete"):
        A = v["arms"]
        h0 = A["Q0_concept"]["hits"]
        out["P1"] = "a" if h0 >= 170 else "b" if h0 >= 120 else "c"
        q0p = A["Q0_concept"]["pull_pts"]

        def pb(p):
            return "a" if p < 20 else ("c" if p >= 0.5 * q0p else "b")

        out["P2"] = pb(A["Q1_concept"]["pull_pts"])
        out["P3"] = pb(A["Q2_concept"]["pull_pts"])
        out["P4"] = {"spotlight": "a", "question-specific": "b", "mixed": "c"}.get(v["overall"], "not scorable")

        def cmp(q):
            d = A[f"{q}_random"]["hits"] - A[f"{q}_concept"]["hits"]
            return "a" if abs(d) <= 20 else ("b" if d < 0 else "c")

        out["P5"], out["P6"] = cmp("Q0"), cmp("Q1")
        out["P7"] = "a" if v["Q1_longest_correct_with_push_pct"] >= v["Q1_longest_correct_no_push_pct"] - 10 else "b"
    md.append("## Prediction scoring (rules committed before the predictions, ab0e61c)\n")
    md.append("| # | researcher | outcome letter | correct? |\n|---|---|---|---|")
    for q in ["P1", "P2", "P3", "P4", "P5", "P6", "P7"]:
        o = out.get(q, "pending")
        ok = "—" if o in ("pending", "not scorable") else ("yes" if o == pred[q] else "no")
        md.append(f"| {q} | {pred[q]} | {o} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "summary.json").write_text(json.dumps({"status": st, "prediction_outcomes": out}, indent=2), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
