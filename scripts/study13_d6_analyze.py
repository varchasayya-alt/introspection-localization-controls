"""Study 13, deviation D6: report the 1B localization runs (S7 on spans 2-10) beside the pre-registered
summary, and the localization size trend recomputed with them (labelled as deviation; the
pre-registered outcomes in results/study13_summary.md stand). Writes results/study13_d6_summary.md.

Usage: python scripts/study13_d6_analyze.py [--results DIR] [--out DIR]
"""
import argparse
import json
from pathlib import Path

from study13_analyze import trend

REPO = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(REPO / "results"))
    ap.add_argument("--out", default=str(REPO / "results"))
    args = ap.parse_args()
    RES, O = Path(args.results), Path(args.out)
    pre = json.loads((RES / "study13_summary.json").read_text())
    md = ["# Study 13 — deviation D6: Llama-3.2-1B localization with S7 on spans 2–10 (generated by scripts/study13_d6_analyze.py)\n",
          "Labelled as a deviation (logs/deviations.md, D6). The pre-registered outcomes (1B localization not testable; "
          "P1/P2 not scorable) stand; these numbers are reported beside them.\n",
          "| setting | S7 (spans 2–10) | arm A | reader | exact copies: injected / reader | main test | intact score | arm C |",
          "|---|---|---|---|---|---|---|---|"]
    d6 = {}
    for s in ("1b_l1", "1b_l2"):
        D = RES / "study13" / f"{s}_d6"
        san = json.loads((D / "sanity_d6.json").read_text()) if (D / "sanity_d6.json").exists() else {}
        lo = (json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}).get("localization") or {}
        d6[s] = lo
        md.append(f"| {s} (D6) | {san.get('S7_spans_2_10_exact_draws')}/20 | {lo.get('A', '—')}/200 | {lo.get('reader', '—')} | "
                  f"{lo.get('exact_n', '—')}: {lo.get('exact_inj', '—')} / {lo.get('exact_reader', '—')} | **{lo.get('main_test', '—')}**"
                  f"{' (' + lo['main_fail_reason'] + ')' if lo.get('main_fail_reason') else ''} | {lo.get('intact_score_pct')} | {lo.get('C', '—')}/200 |")
    r = pre["results"]
    t = trend(d6["1b_l1"].get("intact_score_pct"), (r["3b_l2"].get("loc") or {}).get("intact_score_pct"),
              r["8b_l2"]["loc"]["intact_score_pct"], 20, 5, 10)
    md.append(f"\nSize trend in intact-text localization **with the D6 1B run** (1B layer 1, 3B, 8B): **{t}** "
              f"(pre-registered result: {pre['trend_localization']}).\n")
    a = d6["1b_l1"].get("A")
    if a is not None:
        p1 = "a" if a >= 150 else "b" if a >= 100 else "c" if a >= 50 else "d"
        lo = d6["1b_l1"]
        p2 = {"PASS": "a", "NOT TESTABLE": "d"}.get(lo["main_test"], "b" if lo.get("main_fail_reason") == "injected < 50%" else "c")
        md.append(f"For information only (not scored): under D6, P1 would be '{p1}' (researcher: c) and P2 '{p2}' (researcher: b); "
                  f"P5 would be '{ {'rises': 'a', 'flat': 'b'}.get(t, 'c') }' (researcher: a).\n")
    O.mkdir(parents=True, exist_ok=True)
    (O / "study13_d6_summary.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
