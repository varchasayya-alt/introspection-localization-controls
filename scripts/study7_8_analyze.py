"""Studies 7-8 analysis: the rules in gates/study7_8_plan.md and the prediction scoring rules
committed in predictions.md (6bae069). Writes results/study7_8_summary.md + .json.

Usage: python scripts/study7_8_analyze.py [--results DIR] [--out DIR]
"""
import argparse
import json
from collections import Counter
from pathlib import Path

from gate1_analyze import load
from gate1 import wilson

REPO = Path(__file__).resolve().parents[1]
FINAL_TULU_A = 186  # Study 6, arm A
NAMES = {6: "Tülu-3-8B final (Study 6)", 7: "Tülu-3-8B-SFT (Study 7)", 8: "Tülu-3-8B-DPO (Study 8)"}
PRED = {7: {"Q1": "a", "Q2": "a", "Q3": "a"}, 8: {"Q1": "a", "Q2": "a", "Q3": "a"}}


def study(D):
    st = json.loads((D / "status.json").read_text()) if (D / "status.json").exists() else {}
    san = json.loads((D / "sanity.json").read_text()) if (D / "sanity.json").exists() else {}
    return st, san, st.get("result", {})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=str(REPO / "results"))
    ap.add_argument("--out", default=str(REPO / "results"))
    args = ap.parse_args()
    RES, O = Path(args.results), Path(args.out)
    md = ["# Studies 7–8 — Tülu-3-8B SFT and DPO with the Study 6 protocol: summary "
          "(generated by scripts/study7_8_analyze.py)\n",
          "Same protocol as Study 6: the authors' prompt in Tülu's chat format, layer 2, α 5, words-only push, "
          "vectors recomputed from each checkpoint; 20 fresh draws × 10 positions per study.\n",
          "## Training-stage comparison (200 trials per arm)\n",
          "| checkpoint | sanity | arm A (concept) | reader | exact copies | exact: injected / reader | main test | arm C (random) | activation size |",
          "|---|---|---|---|---|---|---|---|---|"]
    out, data = {}, {}
    for s in (7, 8, 6):
        st, san, v = study(RES / f"study{s}")
        data[s] = (st, san, v)
        norm = san.get("tulu_norm_mean")
        if v.get("complete"):
            k = v["inj_k"]
            lo, hi = wilson(k["A"], 200)
            md.append(f"| {NAMES[s]} | {st.get('sanity')} | **{k['A']}/200 ({k['A'] / 2:.1f}%)**, CI {lo:.1f}–{hi:.1f}% | "
                      f"{v['reader_k_A']}/200 | {v['A_exact_n']} | {v['A_exact_inj_k']} / {v['A_exact_reader_k']} | "
                      f"**{v['main_test']}**{' (' + v['main_fail_reason'] + ')' if v.get('main_fail_reason') else ''} | "
                      f"{k['C']}/200 ({k['C'] / 2:.1f}%) | {norm if norm is None else round(norm, 3)} |")
        else:
            md.append(f"| {NAMES[s]} | {st.get('sanity', 'not run')} | not complete | | | | | | |")
    md.append("")
    for s in (7, 8):
        st, san, v = data[s]
        if not v.get("complete"):
            continue
        D = RES / f"study{s}"
        A, C, R = load(D / "armA_injected.jsonl"), load(D / "armC_injected.jsonl"), load(D / "armA_reader.jsonl")
        base = load(D / "no_injection.jsonl")
        md.append(f"## {NAMES[s]}: details\n")
        md.append(f"S7 clean copies exact: {san.get('S7_clean_copy_all_exact_draws')}/20. Answers (1…10): A "
                  + ",".join(str(Counter(r["pred"] for r in A).get(i, 0)) for i in range(1, 11))
                  + "; C " + ",".join(str(Counter(r["pred"] for r in C).get(i, 0)) for i in range(1, 11))
                  + "; no injection " + ",".join(str(Counter(r["pred"] for r in base).get(i, 0)) for i in range(1, 11)) + "\n")
        md.append("| concept | A injected | A reader | A exact copies | C random |\n|---|---|---|---|---|")
        for c in dict.fromkeys(r["concept"] for r in A):
            md.append(f"| {c} | {sum(r['correct'] for r in A if r['concept'] == c)} | "
                      f"{sum(r['reader_correct'] for r in R if r['concept'] == c)} | "
                      f"{sum(r['exact_target'] for r in R if r['concept'] == c)} | "
                      f"{sum(r['correct'] for r in C if r['concept'] == c)} |")
        md.append("\n| position | " + " | ".join(str(i) for i in range(1, 11)) + " |\n|---|" + "---|" * 10)
        for name, rows, f in (("A", A, "correct"), ("A reader", R, "reader_correct"), ("C", C, "correct")):
            md.append(f"| {name} | " + " | ".join(str(sum(r[f] for r in rows if r["pos"] == i)) for i in range(1, 11)) + " |")
        md.append("")

    # --- prediction scoring (rules committed in predictions.md, 6bae069)
    md.append("## Prediction scoring (rules committed before the predictions, 6bae069)\n")
    md.append("| study | # | researcher | outcome letter | correct? |\n|---|---|---|---|---|")
    for s in (7, 8):
        st, san, v = data[s]
        o = {}
        if v.get("complete"):
            a = v["inj_k"]["A"]
            o["Q1"] = "a" if a >= 150 else "b" if a >= 100 else "c" if a >= 50 else "d"
            o["Q2"] = {"PASS": "a", "NOT TESTABLE": "d"}.get(
                v["main_test"], "b" if v.get("main_fail_reason") == "injected < 50%" else "c")
            d = a - FINAL_TULU_A
            o["Q3"] = "a" if abs(d) <= 20 else ("b" if d < 0 else "c")
        elif str(st.get("sanity", "")).startswith("FAIL"):
            o = {q: "not scorable" for q in PRED[s]}
        out[s] = o
        for q in PRED[s]:
            x = o.get(q, "pending")
            ok = "—" if x in ("pending", "not scorable") else ("yes" if x == PRED[s][q] else "no")
            md.append(f"| {s} | {q} | {PRED[s][q]} | {x} | {ok} |")
    md.append("")
    O.mkdir(parents=True, exist_ok=True)
    (O / "study7_8_summary.md").write_text("\n".join(md), encoding="utf-8")
    (O / "study7_8_summary.json").write_text(json.dumps({"prediction_outcomes": out}, indent=2), encoding="utf-8")
    print("\n".join(md).encode("ascii", "replace").decode())


if __name__ == "__main__":
    main()
